#!/usr/bin/env node
/**
 * Generates src/text/confusables-data.ts from Unicode's confusables.txt (UTS #39 security data).
 *
 *   curl -sSfLo confusables.txt https://www.unicode.org/Public/security/16.0.0/confusables.txt
 *   node scripts/gen-confusables.mjs confusables.txt
 *
 * Only a subset is kept, on purpose: mappings from a NON-ASCII code point to a target made entirely of
 * ASCII. MCPhantom folds look-alikes *into* Latin so that English instruction patterns and ASCII
 * identifiers (keys, URLs) match; it never remaps ASCII itself. The full TR39 skeleton also maps ASCII
 * (`m` → `rn`, `I` → `l`, `0` → `O`), which is right for comparing two skeletons but would break every
 * pattern written against ordinary text.
 *
 * The data is © Unicode, Inc., Unicode License v3 (see NOTICE). The generated file records the source
 * version and SHA-256 so a regeneration is reviewable.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) {
  process.stderr.write('usage: node scripts/gen-confusables.mjs <confusables.txt>\n');
  process.exit(2);
}
const raw = fs.readFileSync(src);
const text = raw.toString('utf8');
const version = /^# Version: (\S+)/m.exec(text)?.[1];
if (!version) throw new Error('no "# Version:" header; is this confusables.txt?');
const sha256 = crypto.createHash('sha256').update(raw).digest('hex');

const isAscii = (s) => /^[\x20-\x7E]+$/.test(s);
const entries = [];
for (const line of text.split('\n')) {
  const m = /^([0-9A-F]{4,6})\s*;\s*([0-9A-F ]+?)\s*;\s*MA\b/.exec(line);
  if (!m) continue;
  const source = parseInt(m[1], 16);
  if (source < 0x80) continue; // never remap ASCII
  const target = m[2].split(' ').map((h) => String.fromCodePoint(parseInt(h, 16))).join('');
  if (!isAscii(target)) continue;
  entries.push([source, target]);
}
entries.sort((a, b) => a[0] - b[0]);

const hex = (n) => '0x' + n.toString(16).toUpperCase().padStart(4, '0');
const out = `// GENERATED by scripts/gen-confusables.mjs — do not edit by hand.
// Source: Unicode confusables.txt ${version} (UTS #39), sha256 ${sha256}
// Data © Unicode, Inc., Unicode License v3 — see NOTICE.
// Subset: non-ASCII code point → ASCII-only target (${entries.length} of the file's mappings).

export const CONFUSABLES_VERSION = '${version}';
export const CONFUSABLES_SHA256 = '${sha256}';

export const CONFUSABLES: readonly (readonly [number, string])[] = [
${entries.map(([s, t]) => `  [${hex(s)}, ${JSON.stringify(t)}],`).join('\n')}
];
`;
const here = path.dirname(fileURLToPath(import.meta.url));
const dest = path.join(here, '..', 'src', 'text', 'confusables-data.ts');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
process.stdout.write(`wrote ${dest}: ${entries.length} mappings from confusables.txt ${version}\n`);
