/**
 * Parsing and rendering for scripts/gen-confusables.mjs, split out so they can be tested
 * (test/confusables-gen.test.ts) without the 1.5 MB Unicode source file.
 */
import crypto from 'node:crypto';

const isAscii = (s) => /^[\x20-\x7E]+$/.test(s);

/**
 * Parses Unicode confusables.txt. Keeps only `MA` mappings from a NON-ASCII code point to a target
 * made entirely of printable ASCII, sorted by source code point. Throws if the version header is
 * missing (not a confusables.txt).
 */
export function parseConfusables(raw) {
  const text = raw.toString('utf8');
  const version = /^# Version: (\S+)/m.exec(text)?.[1];
  if (!version) throw new Error('no "# Version:" header; is this confusables.txt?');
  const sha256 = crypto.createHash('sha256').update(raw).digest('hex');
  const entries = [];
  for (const line of text.split('\n')) {
    const m = /^([0-9A-F]{4,6})\s*;\s*([0-9A-F ]+?)\s*;\s*MA\b/.exec(line);
    if (!m) continue;
    const source = parseInt(m[1], 16);
    if (source < 0x80) continue; // never remap ASCII
    const target = m[2].split(' ').map((h) => String.fromCodePoint(parseInt(h, 16))).join('');
    if (!isAscii(target)) continue;
    entries.push([source, target]);
  }
  entries.sort((a, b) => a[0] - b[0]);
  return { version, sha256, entries };
}

/** Renders the generated TypeScript module (src/text/confusables-data.ts). */
export function renderConfusables({ version, sha256, entries }) {
  const hex = (n) => '0x' + n.toString(16).toUpperCase().padStart(4, '0');
  return `// GENERATED by scripts/gen-confusables.mjs — do not edit by hand.
// Source: Unicode confusables.txt ${version} (UTS #39), sha256 ${sha256}
// Data © Unicode, Inc., Unicode License v3 — see NOTICE.
// Subset: non-ASCII code point → ASCII-only target (${entries.length} of the file's mappings).

export const CONFUSABLES_VERSION = '${version}';
export const CONFUSABLES_SHA256 = '${sha256}';

export const CONFUSABLES: readonly (readonly [number, string])[] = [
${entries.map(([s, t]) => `  [${hex(s)}, ${JSON.stringify(t)}],`).join('\n')}
];
`;
}
